-- Applied to production 2026-11-04. Idempotent definition for source control.
create table if not exists public.activity_update_notes (
  id bigint generated by default as identity primary key,
  activity_row_id text not null references public.activities(row_id) on delete cascade,
  body text not null check (char_length(btrim(body)) between 1 and 4000),
  author_auth_user_id uuid not null default auth.uid(),
  author_name text not null,
  created_at timestamptz not null default now()
);
create index if not exists activity_update_notes_activity_created_idx on public.activity_update_notes(activity_row_id,created_at desc,id desc);
alter table public.activity_update_notes enable row level security;
drop policy if exists activity_update_notes_select_staff on public.activity_update_notes;
create policy activity_update_notes_select_staff on public.activity_update_notes for select to authenticated
using (auth.uid() is not null and app_current_role() in ('admin','operation_manager','authorized_user','finance','activities_manager','domain_manager','instructor_manager','business_development_manager'));
drop policy if exists activity_update_notes_insert_editor on public.activity_update_notes;
create policy activity_update_notes_insert_editor on public.activity_update_notes for insert to authenticated
with check (auth.uid() is not null and author_auth_user_id = auth.uid() and (app_can_edit_direct() or app_can_request_edit())
and exists (select 1 from public.users u where u.auth_user_id=auth.uid() and coalesce(nullif(btrim(u.full_name),''),nullif(btrim(u.name),''))=author_name));
revoke all on public.activity_update_notes from anon, authenticated;
grant select,insert on public.activity_update_notes to authenticated;
grant usage,select on sequence public.activity_update_notes_id_seq to authenticated;
create or replace function public.activity_update_notes_stamp_author()
returns trigger language plpgsql security invoker set search_path=public,pg_temp as $$
declare v_name text;
begin
  select coalesce(nullif(btrim(full_name),''),nullif(btrim(name),'')) into v_name from public.users where auth_user_id=auth.uid() limit 1;
  if v_name is null then raise exception 'activity_update_notes_missing_user'; end if;
  new.author_auth_user_id:=auth.uid();
  new.author_name:=v_name;
  new.created_at:=now();
  return new;
end $$;
drop trigger if exists activity_update_notes_stamp_author_t on public.activity_update_notes;
create trigger activity_update_notes_stamp_author_t before insert on public.activity_update_notes
for each row execute function public.activity_update_notes_stamp_author();
