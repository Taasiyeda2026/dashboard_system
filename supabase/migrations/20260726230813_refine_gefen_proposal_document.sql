-- Refine GEFEN proposal wording so validity and cancellation terms render as
-- compact bullet lists in both the live preview and generated PDF.

update public.proposal_template_sections
set section_body = case section_key
  when 'validity' then
    E' הצעה זו בתוקף עד ליום {{valid_until}}.\n שריון צוותי ההדרכה, מועדי הפעילות והיקף התוכנית יבוצע לפי סדר השלמת הזמנות העבודה במערכת גפ״ן ובכפוף לזמינות.\n כל עוד לא אושרה הזמנת העבודה, לא ניתן להבטיח את השריון ולאחר תום תוקף ההצעה תהיה תעשיידע רשאית להקצות את הקיבולת לבתי ספר אחרים.'
  when 'cancellation_terms' then
    E' בקשה לשינוי או לדחיית מועד תימסר מוקדם ככל האפשר ורצוי לפחות 3 ימי עבודה מראש.\n מפגש שבוטל ביוזמת בית הספר יתואם למועד חלופי במהלך תקופת הפעילות.\n ביטול או שינוי שנמסרו פחות מ-48 שעות לפני המפגש יחייבו אישור בכתב של מנהל/ת בית הספר ויטופלו בתיאום בין הצדדים.\n הפסקת תוכנית או הפחתת היקפה לאחר תחילת הפעילות ייעשו בהודעה בכתב לפחות 30 ימים מראש או בהסכמה בכתב בין הצדדים.\n בתקופת ההודעה המוקדמת יישא בית הספר בתשלום עבור פעילויות שבוצעו או שתוכננו לתקופה זו, בהתאם להזמנת העבודה המאושרת ולהוראות גפ״ן.\n מפגש לא ידווח כמבוצע אלא אם התקיים בפועל או אם הדיווח מותר לפי הוראות גפ״ן.\n במקרה של מצב חירום או הנחיות רשות מוסמכת, יתואם מתווה חלופי בהתאם להוראות גפ״ן, לרבות דחייה, התאמה או מעבר לפעילות מקוונת. פעילות מקוונת תתומחר לפי התעריף החל בגפ״ן, לרבות הפחתה של 10%, ככל שנדרש.'
  else section_body
end,
updated_at = now()
where template_key = 'gefen'
  and section_key in ('validity', 'cancellation_terms');
