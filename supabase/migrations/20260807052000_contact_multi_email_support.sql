create table if not exists public.contact_emails (
  id bigint generated by default as identity primary key,
  contact_id bigint not null references public.contacts_schools(id) on delete cascade,
  email text not null,
  is_primary boolean not null default false,
  source text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists contact_emails_contact_email_key
  on public.contact_emails (contact_id, lower(btrim(email)));
create unique index if not exists contact_emails_one_active_primary_key
  on public.contact_emails (contact_id)
  where is_primary and active;
create index if not exists idx_contact_emails_contact_id
  on public.contact_emails (contact_id);
create index if not exists idx_contact_emails_email_lower
  on public.contact_emails (lower(btrim(email)));

